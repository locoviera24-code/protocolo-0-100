import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const read=path=>readFile(new URL(`../${path}`,import.meta.url),'utf8');
const manifest=JSON.parse(await read('app-version.json'));
const packageJson=JSON.parse(await read('package.json'));
const lock=JSON.parse(await read('package-lock.json'));
const versionScript=await read('app-version.js');
const html=await read('index.html');
const advanced=await read('advanced-features.js');
const worker=await read('sw.js');
const gradle=await read('android-native-wrapper/app/build.gradle');
const release=await read('.github/workflows/build-release-apk.yml');
const readme=await read('README.md');
const handoff=await read('CODEX_HANDOFF.md');
const cacheName=`protocolo-0-100-pwa-${manifest.version}-b${manifest.build}`;

assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
assert.ok(Number.isInteger(manifest.versionCode)&&manifest.versionCode>0);
assert.ok(Number.isInteger(manifest.build)&&manifest.build>0);
assert.equal(packageJson.version,manifest.version);
assert.equal(lock.version,manifest.version);
assert.equal(lock.packages[''].version,manifest.version);
assert.match(versionScript,new RegExp(`version:'${manifest.version.replaceAll('.','\\.')}'`));
assert.match(versionScript,new RegExp(`versionCode:${manifest.versionCode}`));
assert.match(versionScript,new RegExp(`build:${manifest.build}`));
assert.ok(html.indexOf('app-version.js')<html.indexOf('const APP_WEB_VERSION'));
assert.match(html,/APP_WEB_VERSION = window\.APP_VERSION_INFO/);
assert.doesNotMatch(html,/const APP_WEB_VERSION = ['"]\d/);
assert.match(advanced,/APP_VERSION=window\.APP_VERSION_INFO/);
assert.match(worker,/importScripts\('\.\/app-version\.js'\)/);
assert.match(worker,/CACHE_NAME = APP_VERSION_INFO\.cacheName/);
assert.match(gradle,/groovy\.json\.JsonSlurper/);
assert.match(gradle,/versionCode appVersion\.versionCode/);
assert.match(gradle,/versionName appVersion\.version/);
assert.doesNotMatch(gradle,/versionName\s+['"]\d/);
assert.match(release,/require\('\.\/app-version\.json'\)\.version/);
assert.ok(readme.includes(`version actual \`v${manifest.version}\` (build web \`${manifest.build}\`, Android \`${manifest.versionCode}\`)`));
assert.ok(handoff.includes(`Version actual: \`${manifest.version}\` (fuente unica: \`app-version.json\`)`));
assert.ok(handoff.includes(cacheName));
assert.match(html,/id="aboutWebVersion">—</);
assert.match(html,/id="aboutCacheVersion">—</);
console.log(`Version alineada: ${manifest.version}, Android ${manifest.versionCode}, build/cache ${manifest.build}.`);
